#!/usr/bin/env python3
"""Pin this checkout to one Action-Build SM8550 5.15 analogue + matching ROM."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sub_file(path: Path, mapping: dict[str, str]) -> None:
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8")
    orig = text
    for a, b in mapping.items():
        text = text.replace(a, b)
    if text != orig:
        path.write_text(text)


def lock_workflow(file: str) -> None:
    p = ROOT / ".github/workflows/build-kernel-gt5.yml"
    text = p.read_text(encoding="utf-8")
    text = re.sub(
        r"        default: oneplus_ace2_pro_b\n        options:\n(?:          - .+\n)+",
        f"        default: {file}\n        options:\n          - {file}\n",
        text,
        count=1,
    )
    # also replace whatever default is now
    text = re.sub(
        r"(      FILE:\n        type: choice\n        description: .+\n        required: true\n        default: )[^\n]+",
        rf"\1{file}",
        text,
        count=1,
    )
    text = re.sub(
        r"        options:\n(?:          - \S+\n)+",
        f"        options:\n          - {file}\n",
        text,
        count=1,
    )
    p.write_text(text)


def lock_fetch(file: str) -> None:
    p = ROOT / "scripts/00-fetch.sh"
    text = p.read_text(encoding="utf-8")
    text = re.sub(r"FILE=\$\{FILE:-[^}]+\}", f"FILE=${{FILE:-{file}}}", text, count=1)
    p.write_text(text)


def write_readme(file: str, android: str, api: int, kmi: str, note: str) -> None:
    (ROOT / "README.md").write_text(
        f"""# Realme GT5 — kernel `{file}` + ROM ossi

Branch for **one** Action-Build SM8550 5.15 OGKI analogue.

| | |
|---|---|
| Analogue | `{file}` ({note}) |
| Android | {android} (API {api}) |
| KMI | `{kmi}` |
| SoC | SM8550 kalama |
| Device | ossi / RMX3820 / RE5C33 |
| Root | YukiSU LKM `CONFIG_KSU=m` |
| Kernel | OEM OGKI `oplus_build_kernel.sh kalama gki` — **not** Google GKI |
| ROM | `rom/device/realme/ossi` — `lunch infinity_ossi-userdebug` |
| metadata | **ext4** (stock). Do not use Lineage f2fs fstab |

```bash
export FILE={file}
scripts/00-fetch.sh
scripts/10-patch.sh
scripts/20-build.sh
# drop Image into the ROM prebuilt slot (kernelsu.ko is loaded by ksud, not init)
cp Image rom/device/realme/ossi/prebuilt/Image
scripts/30-package.sh
scripts/rom-adapt.sh
```

CI: **Build Realme GT5 OGKI (YukiSU)** — `FILE` locked to `{file}`.
""",
        encoding="utf-8",
    )


def main() -> int:
    if len(sys.argv) != 6:
        print("usage: specialize-branch.py FILE ANDROID API KMI NOTE", file=sys.stderr)
        return 2
    file, android, api_s, kmi, note = sys.argv[1:]
    api = int(api_s)

    kernel = {
        "codename": "ossi",
        "model": "RMX3820",
        "board": "RE5C33",
        "soc": "sm8550",
        "cpud": "kalama",
        "file": file,
        "android": android,
        "api": api,
        "kmi": kmi,
        "build_method": "gki",
        "build_method_meaning": "OEM OGKI flavor of oplus_build_kernel.sh, NOT Google generic GKI",
        "root": "YukiSU LKM CONFIG_KSU=m + Kasumi + YukiZygisk",
        "metadata_fs": "ext4",
        "note": note,
    }
    (ROOT / "kernel.json").write_text(json.dumps(kernel, indent=2) + "\n")

    (ROOT / "rom/device/realme/ossi/branch.mk").write_text(
        f"# Autogenerated for branch 5.15-{file}\n"
        f"BOARD_KERNEL_ANALOGUE := {file}\n"
        f"PRODUCT_SHIPPING_API_LEVEL := {api}\n"
        f"BOOT_SECURITY_PATCH := 2026-09-01\n"
        f"VENDOR_SECURITY_PATCH := $(BOOT_SECURITY_PATCH)\n"
    )

    device_mk = ROOT / "rom/device/realme/ossi/device.mk"
    text = device_mk.read_text()
    text = re.sub(
        r"PRODUCT_SHIPPING_API_LEVEL := \d+",
        f"PRODUCT_SHIPPING_API_LEVEL := {api}",
        text,
    )
    device_mk.write_text(text)

    inf = ROOT / "rom/device/realme/ossi/infinity_ossi.mk"
    t = inf.read_text()
    t = re.sub(r'BuildDesc="RMX3820-user [^"]+"', f'BuildDesc="RMX3820-user {android}"', t)
    t = re.sub(
        r"BuildFingerprint=realme/RMX3820/RE5C33:[^/]+/",
        f"BuildFingerprint=realme/RMX3820/RE5C33:{android}/",
        t,
    )
    inf.write_text(t)

    vend = ROOT / "rom/vendor/realme/ossi/ossi-vendor.mk"
    vt = vend.read_text()
    vt = re.sub(r"Android \d+", f"Android {android}", vt)
    vend.write_text(vt)

    lock_workflow(file)
    lock_fetch(file)
    write_readme(file, android, api, kmi, note)
    print(f"specialized {file} android={android} api={api}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
