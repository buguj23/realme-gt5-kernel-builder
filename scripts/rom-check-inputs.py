#!/usr/bin/env python3
"""Check or render the stock baseline used by the local and CI ROM builders."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import urlsplit

from rom_inputs import baseline, require, sha256, stock_payload, verify_stock


def manifest_source(source, manifest, branch):
    manifests = source / ".repo/manifests"

    def config(key):
        return subprocess.check_output(
            ["git", "-C", manifests, "config", "--local", "--get", key],
            text=True, stderr=subprocess.DEVNULL).strip()

    got, expected = map(urlsplit, (config("remote.origin.url"), manifest))
    matching_origin = (got.hostname == expected.hostname and
                       got.path.rstrip("/").removesuffix(".git").lower() ==
                       expected.path.rstrip("/").removesuffix(".git").lower())
    require(matching_origin, "repo manifest origin does not match the selected stock baseline")
    require(config("branch.default.merge") == f"refs/heads/{branch}",
            f"repo source tree must track {branch}")


def verified_blobs(blobs, digest):
    manifest = json.loads((blobs / ".rom-blob-identity.json").read_text())
    require(manifest["schema"] == 3 and manifest["stock_payload"] == digest,
            "blob dump identity differs from the stock OTA")
    actual = {str(path.relative_to(blobs)): path for path in blobs.rglob("*")
              if path.is_file() and path != blobs / ".rom-blob-identity.json"}
    require(actual and actual.keys() == manifest["files"].keys(), "blob dump inventory differs")
    for name, path in actual.items():
        require(not path.is_symlink() and sha256(path) == manifest["files"][name],
                f"stock blob differs: {name}")
    return manifest


def verify_vendor(vendor, blob_list):
    proprietary = vendor / "proprietary"
    for line in blob_list.read_text().splitlines():
        line = line.strip().lstrip("-+")
        if not line or line.startswith("#"):
            continue
        path = re.split(r"[;|]", line, maxsplit=1)[0].rsplit(":", 1)[-1].strip()
        if "/" in path:
            final = (proprietary / path).resolve()
            require(final.is_relative_to(proprietary.resolve()) and final.is_file() and final.stat().st_size,
                    f"extract-utils did not generate required vendor file {path}")
    blueprint = (vendor / "Android.bp").read_text()
    makefile = (vendor / "ossi-vendor.mk").read_text()
    paths = set(re.findall(r'"(proprietary/[^"\n]+)"', blueprint))
    paths.update(re.findall(r'vendor/realme/ossi/(proprietary/[^:\s]+):', makefile))
    require(paths, "generated vendor makefiles contain no blob sources")
    for path in sorted(paths):
        require((vendor / path).is_file(), f"vendor makefile refers to missing source {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="operation", required=True)
    profile = commands.add_parser("profile")
    profile.add_argument("--branch", required=True)
    profile.add_argument("--field")
    profile.add_argument("--stage-device", type=Path)
    source = commands.add_parser("source")
    source.add_argument("--src", type=Path, required=True)
    selection = source.add_mutually_exclusive_group(required=True)
    selection.add_argument("--branch")
    selection.add_argument("--manifest")
    source.add_argument("--source-branch")
    stock = commands.add_parser("stock")
    stock.add_argument("--branch", required=True)
    stock.add_argument("--stock-images", type=Path, required=True)
    stock.add_argument("--payload-metadata", type=Path)
    stock.add_argument("--blobs", type=Path)
    stock.add_argument("--blob-list", type=Path)
    vendor = commands.add_parser("vendor")
    vendor.add_argument("--vendor", type=Path, required=True)
    vendor.add_argument("--blob-list", type=Path, required=True)
    args = parser.parse_args()
    if args.operation == "profile":
        spec = baseline(args.branch)
        if args.stage_device:
            (args.stage_device / "branch.mk").write_text(
                f"# Generated by rom-check-inputs.py from official/kernels.json\n"
                f"BOARD_KERNEL_ANALOGUE := {spec['file']}\n"
                f"BOOT_SECURITY_PATCH := {spec['security_patch']}\n"
                "VENDOR_SECURITY_PATCH := $(BOOT_SECURITY_PATCH)\n")
            product = spec["product"]
            lunch = f"{product}-userdebug" if spec["android"] != "14" else f"{product}-trunk_staging-userdebug"
            (args.stage_device / "AndroidProducts.mk").write_text(
                f"PRODUCT_MAKEFILES := $(LOCAL_DIR)/{product}.mk\nCOMMON_LUNCH_CHOICES := {lunch}\n")
        elif args.field:
            print(spec[args.field])
        else:
            print(json.dumps(spec))
    elif args.operation == "source":
        if args.branch:
            spec = baseline(args.branch)
            manifest_source(args.src, spec["source_manifest"], spec["source_branch"])
        else:
            require(args.source_branch, "--source-branch is required with --manifest")
            manifest_source(args.src, args.manifest, args.source_branch)
    elif args.operation == "vendor":
        verify_vendor(args.vendor, args.blob_list)
    else:
        payload = stock_payload(args.stock_images, args.branch, args.payload_metadata)
        verify_stock(args.stock_images, payload, ("boot", "init_boot", "vendor_boot", "dtbo"))
        if args.blobs:
            manifest = verified_blobs(args.blobs, payload["sha256"])
            if args.blob_list:
                require(sha256(args.blob_list) == manifest["list_sha256"], "blob list differs from the materialized dump")
        print(f"Stock OTA identity verified for {args.branch}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(f"FAIL: ROM inputs: {error}", file=sys.stderr)
        raise SystemExit(1)
